namespace Arts6311.Domain.Managers.Audit;

/// <summary>
/// An immutable record of one sensitive action (auth.md "Sensitive operations"): deletes and archives, seat
/// adjustments, outbox replay or discard, user and role changes, secret rotation, redirect changes. Written once
/// and never updated or deleted; a correction is a new row.
/// </summary>
/// <remarks>
/// <para>
/// Immutability is <strong>application-enforced only</strong>: <see cref="AuditLogImmutabilityInterceptor"/>
/// rejects tracked updates and deletes on <c>SaveChanges</c>. <c>ExecuteUpdate</c>, <c>ExecuteDelete</c>, raw
/// SQL and other connections bypass it, and there is no database-level guard yet (ADR 0017, DECIDE). Never write
/// to this table any other way than <see cref="IAuditWriter"/>.
/// </para>
/// </remarks>
/// <remarks>
/// <see cref="Summary"/>, <see cref="BeforeReference"/> and <see cref="AfterReference"/> never carry secrets,
/// tokens, card data, email bodies or provider payloads. Before/after are pointers (an id, a row version) or short
/// field-name diffs, not the content that changed.
/// </remarks>
/// <seealso cref="AuditPolicy"/>
public sealed class AuditLog
{
    /// <summary>Generated by EF on insert as a sequential GUID, so the clustered index stays in order.</summary>
    public Guid Id { get; set; }

    /// <summary>The acting user, or <c>null</c> for a system or background action. Not a foreign key: the row outlives the account.</summary>
    public string? ActorUserId { get; set; }

    /// <summary>A stable code, e.g. <c>artist.archived</c>.</summary>
    public string Action { get; set; } = string.Empty;

    public string ResourceType { get; set; } = string.Empty;

    public string ResourceId { get; set; } = string.Empty;

    /// <summary>Ties the entry to the request or outbox message that produced it.</summary>
    public Guid CorrelationId { get; set; }

    public DateTimeOffset OccurredAt { get; set; }

    public string Summary { get; set; } = string.Empty;

    public string? BeforeReference { get; set; }

    public string? AfterReference { get; set; }
}

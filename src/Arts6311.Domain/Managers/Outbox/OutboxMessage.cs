namespace Arts6311.Domain.Managers.Outbox;

/// <summary>
/// A durable internal event awaiting delivery to exactly one <see cref="IOutboxMessageHandler"/>. The outbox
/// table is the queue (ADR 0003): there is no broker. Staged only through <see cref="IOutboxWriter"/>, drained
/// only by <see cref="IOutboxDispatcher"/>.
/// </summary>
/// <remarks>
/// <see cref="PayloadJson"/> carries ids only — never content, prices, tokens, card data or email bodies — and
/// <see cref="LastError"/> never carries provider messages, hosts, keys or tokens (outbox.md).
/// </remarks>
public sealed class OutboxMessage
{
    /// <summary>
    /// Generated by EF as a sequential GUID when the row is staged, so it is known before the save and the
    /// clustered index stays in order. Also the Square idempotency key for whatever the handler sends.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>The routing key a handler is registered under (keyed DI), kebab-case <c>area.event</c>.</summary>
    public string Type { get; set; } = string.Empty;

    public string PayloadJson { get; set; } = string.Empty;

    /// <summary>The enqueuing request's correlation id (<c>ICorrelationContext</c>): the W3C trace id when there is one.</summary>
    public Guid CorrelationId { get; set; }

    /// <summary>
    /// The enqueuing span's W3C <c>traceparent</c>, captured by <see cref="IOutboxWriter"/>, so the handler's span is
    /// its child and one trace runs request → message → handler (ADR 0019). <c>null</c> when nothing was tracing; the
    /// dispatcher then parents the handler on <see cref="CorrelationId"/> alone.
    /// </summary>
    public string? TraceParent { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Not eligible for dispatch before this instant — the initial enqueue time, or a backoff retry time.</summary>
    public DateTimeOffset AvailableAt { get; set; }

    public int Attempts { get; set; }

    public OutboxMessageStatus Status { get; set; }

    /// <summary>The claim token of the dispatch pass currently holding this message, if <see cref="Status"/> is Leased.</summary>
    public Guid? LeasedBy { get; set; }

    public DateTimeOffset? LeaseExpiresAt { get; set; }

    public DateTimeOffset? CompletedAt { get; set; }

    public string? LastError { get; set; }
}
